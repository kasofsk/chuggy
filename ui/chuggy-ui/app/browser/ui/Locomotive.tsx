/**
 * The favicon's own locomotive, inlined at the card's scale and animated as a
 * sprite, so the console's first paint says a read is in flight rather than
 * only saying so in words.
 *
 * The engine holds still and the ground passes under it, rather than the
 * engine crossing the card: a card's width belongs to layout, not to a
 * stylesheet, so a keyframe that travelled it would have to measure the card
 * from React and hold that measurement in state. A ground that tiles needs no
 * measurement — it is one `@keyframes` rule sliding a repeating background
 * by one tile, in `Locomotive.css`.
 *
 * The engine itself is a sprite sheet rather than a single drawing:
 * `locomotiveFrames` holds every frame's `rect`s side by side in the markup,
 * and `Locomotive.css` slides a window past them one whole frame at a time
 * with `steps()` — no per-frame React state, no timer, no style attribute.
 * The pace is `--duration-chuff` in `tokens.css`, zeroed under reduced
 * motion; at zero no animation is applied, so the sprite rests on its first
 * frame — drawn whole, never mid-puff.
 *
 * The first frame is a copy of `public/favicon.svg`'s `rect`s rather than a
 * shared import: an SVG file is not import-able as markup without a bundler
 * plugin this console does not otherwise need. If that frame ever changes,
 * the favicon changes with it in the same commit.
 *
 * `LocomotiveEngine` is the sprite alone, exported so a caller elsewhere in
 * the console — the strip above a waiting composer — draws the same engine
 * without the ground this card slides under it, and without a second copy of
 * the drawing to keep in step with the favicon.
 */

