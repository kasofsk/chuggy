/**
 * The one door a member asks through. It forks the project's lead under the
 * asker's own principal, writes the roster itself, and enqueues exactly one
 * turn — which is what makes one turn per inquiry a property of the mailbox
 * rather than of a runtime bound: nothing else in the tree enqueues a second.
 */
const askDoor = [
  `CREATE FUNCTION ${leadInquiryOpenFunction}(
     in_tenant text,in_project text,in_principal text,in_session text,
     in_turn text,in_question text)
     RETURNS TABLE(opened text,ordinal bigint,session text)
     LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public,pg_temp AS $$
     DECLARE standing bigint; parent record; head bigint; held bigint; answered record;
     BEGIN
       SELECT t.ordinal INTO standing FROM session_turn t
         JOIN agent_session s ON s.tenant=t.tenant AND s.project=t.project
                             AND s.session=t.session
        WHERE s.tenant=in_tenant AND s.project=in_project AND s.session=in_session
          AND s.kind='Inquiry' AND s.principal=in_principal AND t.turn=in_turn;
       IF FOUND THEN
         RETURN QUERY SELECT 'AlreadyOpen'::text,standing,in_session; RETURN;
       END IF;
       SELECT s.session,s.state,s.agent_reference,s.credential_slot,
              s.account,s.cluster,s.system_prompt
         INTO parent FROM agent_session s
        WHERE s.tenant=in_tenant AND s.project=in_project AND s.kind='Lead'
        FOR UPDATE;
       IF NOT FOUND THEN
         RETURN QUERY SELECT 'NoLead'::text,NULL::bigint,NULL::text; RETURN;
       END IF;
       IF parent.state<>'Open' THEN
         RETURN QUERY SELECT 'LeadClosed'::text,NULL::bigint,parent.session; RETURN;
       END IF;
       SELECT ${settledHead(
         "t.tenant=in_tenant AND t.project=in_project",
         "parent.session",
       )} INTO head;
       IF parent.agent_reference IS NULL OR head=0 THEN
         RETURN QUERY SELECT 'LeadNotStarted'::text,NULL::bigint,parent.session;
         RETURN;
       END IF;
       SELECT count(*) INTO held FROM agent_session s
        WHERE s.tenant=in_tenant AND s.project=in_project
          AND s.kind='Inquiry' AND s.principal=in_principal AND s.state='Open';
       IF held>=${inquiriesOpenPerMemberMax} THEN
         RETURN QUERY SELECT 'InFlight'::text,NULL::bigint,NULL::text; RETURN;
       END IF;
       INSERT INTO agent_session
         (tenant,project,session,kind,principal,parent_session,capabilities,
          credential_slot,account,cluster,system_prompt)
       VALUES(in_tenant,in_project,in_session,'Inquiry',in_principal,parent.session,
              ${inquiryRosterLiteral},parent.credential_slot,parent.account,parent.cluster,
              parent.system_prompt || ${appendedObjectives});
       SELECT * INTO answered FROM ${sessionTurnEnqueueFunction}(
         in_tenant,in_project,in_session,in_turn,'Inquiry',in_question);
       RETURN QUERY SELECT 'Opened'::text,answered.ordinal,in_session;
     END $$`,
];

/**
 * What one inquiry answers with, which is the question, the answer and what the
 * turn cost. The question is the turn's INPUT DOCUMENT and this read hands it
 * over unparsed: the interpreter composes that document and the interpreter
 * reads it back, exactly as the plane stores a turn's input without reading it.
 */
const inquiryColumns = `session text,principal text,asker text,state text,
                   turn text,turn_state text,ordinal bigint,input text,result text,
                   failure text,asked_at timestamptz,model text,tokens bigint,
                   cost_micros bigint,duration_ms bigint,tools text[]`;

const inquirySelection = `SELECT s.session,s.principal,m.authority_subject,s.state,
              t.turn,t.state,t.ordinal,t.input,t.result,t.failure,t.enqueued_at,
              t.model,t.tokens,t.cost_micros,t.duration_ms,t.tools
         FROM agent_session s
         JOIN agent_session parent
           ON parent.tenant=s.tenant AND parent.project=s.project
          AND parent.session=s.parent_session AND parent.kind='Lead'
         JOIN session_turn t
           ON t.tenant=s.tenant AND t.project=s.project AND t.session=s.session
         LEFT JOIN project_membership m
           ON m.tenant=s.tenant AND m.project=s.project AND m.principal=s.principal
        WHERE s.tenant=in_tenant AND s.project=in_project`;

const inquiryReads = [
  `CREATE FUNCTION ${leadInquiriesReadFunction}(
     in_tenant text,in_project text,in_max bigint)
     RETURNS TABLE(${inquiryColumns})
     LANGUAGE sql STABLE SECURITY DEFINER
     SET search_path=pg_catalog,public,pg_temp AS $$
       ${inquirySelection}
        ORDER BY t.enqueued_at DESC,s.session DESC
        LIMIT least(coalesce(in_max,${inquiriesAnsweredMax}),${inquiriesAnsweredMax})
     $$`,
  `CREATE FUNCTION ${leadInquiryReadFunction}(
     in_tenant text,in_project text,in_session text)
     RETURNS TABLE(${inquiryColumns})
     LANGUAGE sql STABLE SECURITY DEFINER
     SET search_path=pg_catalog,public,pg_temp AS $$
       ${inquirySelection} AND s.session=in_session
     $$`,
];

