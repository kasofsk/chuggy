/**
 * An inquiry against a lead: the door that forks one, the reads a member draws
 * it from, and the two walls that make a fork a thing that reads.
 *
 * TWO READS WIDEN TO THE PARENT AND THE WRITE DOES NOT. `read_session_store`
 * and `list_session_streams` answer the bearer's own session UNION the parent
 * of an `Inquiry`; `record_session_store_batch` is untouched and still writes
 * under `bound.session` alone. That asymmetry is the whole control, and a
 * migration that widened the third would end the slice's argument — so the two
 * are dropped and recreated here and the third is not named.
 *
 * THE STORE THE FORK WRITES IS REFUSED AND NOT SWEPT. A `BEFORE INSERT` trigger
 * raises for a session whose kind is `Inquiry`, so an inquiry's transcript is
 * never written and retention over it is not load-bearing. The pod discards its
 * own appends as well, and the pod is the thing being controlled, so the pod's
 * discard saves the wire and the trigger is the control. The answer a member
 * came for lives on the turn row, which is where it always was.
 *
 * THE PARENT IS READ TO A WHOLE TURN AND NOT TO ITS HEAD. A lead flushes
 * eagerly, so a lead mid-turn has batches standing that end inside an exchange,
 * and a fork resumed over those starts from a truncated assistant message. So
 * the parent read stops at `max(batch_last)` over the parent's settled turns,
 * and answers nothing where there is none. A session reading its OWN stream is
 * not bounded this way: its own batches are its own history and there is no
 * half-written exchange for it to resume over that it did not write.
 *
 * THE DOOR AND THE STORE AGREE BY SHARING ONE TEST. `LeadNotStarted` is exactly
 * the condition under which that ceiling is zero — no runtime reference, or no
 * settled turn that flushed a batch — so a lead the door lets a member fork is
 * a lead the store has something to answer with.
 *
 * `AlreadyOpen` IS TESTED BEFORE THE LEAD IS RESOLVED AT ALL. A retried `POST`
 * must answer the ordinal it already has, and a lead closed between the first
 * attempt and the retry would otherwise turn a fork that exists into
 * `LeadClosed` — telling a member their question was refused when it is already
 * queued. The pre-check matches on the principal and the turn, so a session
 * identity another principal minted falls through to the insert and RAISES
 * against 058's `agent_session_identity_is_never_reused` rather than being
 * answered.
 *
 * `open_lead_inquiry` TAKES NO ROSTER, NO ACCOUNT AND NO CREDENTIAL SLOT. The
 * API may open a session for the very principal that asked, which grants
 * nothing the caller does not already hold, and may not choose what that
 * session may do. The roster is this migration's own array literal generated
 * from `inquiryCapabilities`, and the slot, the account and the cluster are
 * COPIED FROM THE LEAD'S OWN ROW rather than drawn from the project's capacity
 * account: the fork reads the parent's store, the store's bytes sit on the
 * artifacts volume of the cluster the parent runs on, and a fork placed
 * elsewhere would resume nothing.
 *
 * THE OBJECTIVES ARE DERIVED FROM `inquirySystemPrompt` AND NOT RESPELLED. What
 * a fork is told beside the lead's own objectives is taken from that function
 * at build time, with a guard that it still appends; a prefix composed one way
 * in the interpreter and another in SQL is two prompts, and the pod would run
 * under whichever was written last.
 *
 * A GENERATED CHECK IS REPLACED WHERE IT WAS LAST WRITTEN.
 * `agent_session_prompt_is_bounded` was generated by 061 from
 * `sessionPromptCeilings`, and an inquiry's ceiling is the lead's plus what
 * being a fork means — so a fresh installation already holds the wide check and
 * one that ran 061 holds the narrow one for ever unless this replaces it. The
 * device is 059's, 061's and 062's and the reason has not changed.
 *
 * THE CLOSE IS A TRIGGER AND NOT A SWEEP. An inquiry whose one turn has ended
 * takes no other, and leaving it `Open` leaves a bearer that authenticates and
 * an idle pod the reaper has to find. It must NOT fire on `Claimed → Queued`:
 * an attempt lost mid-turn returns the turn to the mailbox, and closing there
 * would turn a lost pod into a lost answer. It fires for `kind='Inquiry'`
 * alone, because a lead's or a thread's turn ending is not the end of anything.
 *
 * A LISTING LEFT JOINS THE MEMBERSHIP, so an inquiry whose asker's membership
 * has been revoked is answered with no asker rather than hidden — 062's
 * argument for a thread's owner, for the same reason: a fork that ran under a
 * project's account is a fact its members are owed.
 */

