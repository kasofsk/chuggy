/** The states a turn is in when the exchange it names is whole. */
const settledTurnStates = "('Answered','Failed')";

/**
 * The last batch a session's SETTLED turns flushed, which is the head a fork
 * may resume from. It is ONE expression used by the store read's ceiling and by
 * the door's `LeadNotStarted`, so the two cannot come to disagree about what
 * there is to fork from; zero means there is no whole exchange to read.
 */
export function settledHead(partition: string, session: string): string {
  return `(SELECT coalesce(max(t.batch_last),0) FROM session_turn t
                WHERE ${partition} AND t.session=${session}
                  AND t.state IN ${settledTurnStates})`;
}

/** The states a turn is in when it will take no further attempt. */
const endedTurnStates = "('Answered','Failed','Abandoned')";

/** The roster an inquiry is opened with, rendered as the literal the definer writes. */
export const inquiryRosterLiteral = `ARRAY[${schemaTextSet([
  ...inquiryCapabilities,
])}]::text[]`;

/** A text no set of composed objectives contains, standing in for the lead's own. */
const leadPromptProbe = "the lead's own objectives";

/** The dollar-quoting tag the appended objectives are written under. */
const promptTag = "$inquiry_objectives$";

/**
 * What `inquirySystemPrompt` puts after the lead's own objectives, taken from
 * that function rather than written again here, and refused at build time if it
 * ever stops being an append or contains the tag it is quoted with.
 */
export const appendedObjectives = ((): string => {
  const composed = inquirySystemPrompt(leadPromptProbe);
  if (!composed.startsWith(leadPromptProbe))
    throw new Error(
      "migration 063: an inquiry's objectives no longer begin with the lead's own",
    );
  const appended = composed.slice(leadPromptProbe.length);
  if (appended.includes(promptTag))
    throw new Error(
      "migration 063: an inquiry's objectives contain the tag they are quoted with",
    );
  return `${promptTag}${appended}${promptTag}`;
})();

/**
 * The sessions one bearer may read a store of: its own, and its parent's — the
 * parent arm carrying the ceiling the read is bounded by and the own arm none,
 * so one join answers both and neither predicate is written twice. It needs no
 * kind test: 058's `agent_session_parent_is_whole` makes `parent_session`
 * non-null exactly for an `Inquiry`, so the parent join IS the kind, and that
 * constraint is where a kind later carrying a parent widens this.
 */
const readableSessions = `(
       SELECT k.session AS session,NULL::bigint AS ceiling
       UNION ALL
       SELECT s.parent_session,
              ${settledHead(
                "t.tenant=s.tenant AND t.project=s.project",
                "s.parent_session",
              )}
         FROM agent_session s
        WHERE s.tenant=k.tenant AND s.project=k.project AND s.session=k.session)`;

/**
 * The runtime reference a fork resumes from, which is its PARENT'S and never
 * its own — so an attempt following a lost one forks again from the lead rather
 * than resuming a fork whose store holds nothing. It needs no kind test for the
 * reason `readableSessions` gives: a session with no parent answers null here.
 */
const forkFrom = `(SELECT p.agent_reference FROM agent_session p
                WHERE p.tenant=s.tenant AND p.project=s.project
                  AND p.session=s.parent_session)`;

/**
 * The plane boundaries a fork changes, dropped and recreated because each is a
 * `RETURNS TABLE` function whose shape or whose session set moves — the same
 * device 059 and 061 use, with the grants re-issued rather than assumed to
 * survive.
 *
 * THE LISTING IS THE PARENT'S STREAMS WHOLE AND THE READ IS BOUNDED, because a
 * count here is whether a stream exists and not a length the resume trusts: the
 * pod asks each named stream for its batches and takes what the bounded read
 * answers, so a stream an unsettled turn alone wrote loads nothing rather than
 * loading half an exchange.
 */
const forkReads = [
  `DROP FUNCTION ${sessionAttemptReadFunction}(text)`,
  `CREATE FUNCTION ${sessionAttemptReadFunction}(in_secret_digest text)
     RETURNS TABLE(tenant text,project text,session text,attempt text,generation bigint,
                   kind text,principal text,capabilities text[],credential_slot text,
                   agent_reference text,system_prompt text,fork_from text,live boolean)
     LANGUAGE sql STABLE SECURITY DEFINER
     SET search_path=pg_catalog,public,pg_temp AS $$
       SELECT a.tenant,a.project,a.session,a.attempt,a.generation,s.kind,s.principal,
              s.capabilities,s.credential_slot,s.agent_reference,s.system_prompt,
              ${forkFrom},
              (a.state IN ('Placing','Running') AND s.state='Open'
               AND a.recovery_epoch=(SELECT epoch FROM recovery_epoch
                                      ORDER BY ordinal DESC LIMIT 1))
         FROM session_attempt a
         JOIN agent_session s ON s.tenant=a.tenant AND s.project=a.project
                             AND s.session=a.session
        WHERE a.bearer_secret_digest=in_secret_digest
     $$`,
  `DROP FUNCTION ${sessionStoreReadFunction}(text,bigint,text,bigint,bigint)`,
  `CREATE FUNCTION ${sessionStoreReadFunction}(
     in_secret_digest text,in_generation bigint,in_stream text,
     in_after bigint,in_limit bigint)
     RETURNS TABLE(batch bigint,digest text,bytes bigint)
     LANGUAGE sql SECURITY DEFINER SET search_path=pg_catalog,public,pg_temp AS $$
       SELECT b.batch,b.digest,b.bytes
         FROM ${sessionAttemptBindingFunction}(in_secret_digest,in_generation) k
         CROSS JOIN LATERAL ${readableSessions} readable
         JOIN session_store_batch b ON b.tenant=k.tenant AND b.project=k.project
                                   AND b.session=readable.session
        WHERE b.stream=in_stream AND b.batch>coalesce(in_after,0)
          AND (readable.ceiling IS NULL OR b.batch<=readable.ceiling)
        ORDER BY b.batch
        LIMIT least(coalesce(in_limit,${sessionStorePageBatchesMax}),
                    ${sessionStorePageBatchesMax})
     $$`,
  `DROP FUNCTION ${sessionStreamListFunction}(text,bigint,bigint)`,
  `CREATE FUNCTION ${sessionStreamListFunction}(
     in_secret_digest text,in_generation bigint,in_max bigint)
     RETURNS TABLE(stream text,batches bigint)
     LANGUAGE sql SECURITY DEFINER SET search_path=pg_catalog,public,pg_temp AS $$
       SELECT b.stream,count(*)::bigint
         FROM ${sessionAttemptBindingFunction}(in_secret_digest,in_generation) k
         CROSS JOIN LATERAL ${readableSessions} readable
         JOIN session_store_batch b ON b.tenant=k.tenant AND b.project=k.project
                                   AND b.session=readable.session
        GROUP BY b.stream ORDER BY b.stream
        LIMIT least(coalesce(in_max,${sessionStoreStreamsAnswered}),
                    ${sessionStoreStreamsAnswered})
     $$`,
];

/** The two walls the pod is not what enforces: nothing written, and nothing left open. */
const inquiryWalls = [
  `CREATE FUNCTION ${inquiryStoreRefusalFunction}() RETURNS trigger
     LANGUAGE plpgsql SET search_path=pg_catalog,public,pg_temp AS $$
     BEGIN
       IF EXISTS(SELECT 1 FROM agent_session s
                  WHERE s.tenant=NEW.tenant AND s.project=NEW.project
                    AND s.session=NEW.session AND s.kind='Inquiry') THEN
         RAISE EXCEPTION
           'session % is an inquiry, and an inquiry answers aside rather than keeping a transcript',
           NEW.session USING ERRCODE = 'integrity_constraint_violation';
       END IF;
       RETURN NEW;
     END $$`,
  `ALTER FUNCTION ${inquiryStoreRefusalFunction}() OWNER TO ${boundaryOwnerRole}`,
  `REVOKE ALL ON FUNCTION ${inquiryStoreRefusalFunction}() FROM PUBLIC`,
  `CREATE TRIGGER session_store_batch_is_never_an_inquiry_s
     BEFORE INSERT ON session_store_batch
     FOR EACH ROW EXECUTE FUNCTION ${inquiryStoreRefusalFunction}()`,
  `CREATE FUNCTION ${inquiryCloseFunction}() RETURNS trigger
     LANGUAGE plpgsql SET search_path=pg_catalog,public,pg_temp AS $$
     BEGIN
       UPDATE agent_session s SET state='Closed',closed_at=now()
        WHERE s.tenant=NEW.tenant AND s.project=NEW.project
          AND s.session=NEW.session AND s.kind='Inquiry';
       RETURN NULL;
     END $$`,
  `ALTER FUNCTION ${inquiryCloseFunction}() OWNER TO ${boundaryOwnerRole}`,
  `REVOKE ALL ON FUNCTION ${inquiryCloseFunction}() FROM PUBLIC`,
  `CREATE TRIGGER inquiry_closes_when_its_turn_ends
     AFTER UPDATE OF state ON session_turn
     FOR EACH ROW WHEN (NEW.state IN ${endedTurnStates})
     EXECUTE FUNCTION ${inquiryCloseFunction}()`,
];

